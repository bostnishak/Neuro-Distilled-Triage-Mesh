class MerkleHash(BaseModel):
    """Cryptographic SHA-256 hash digest value object."""
    model_config = ConfigDict(strict=True, frozen=True)

    digest: str = Field(..., min_length=64, max_length=64)

    @field_validator("digest")
    @classmethod
    def validate_hex(cls, v: str) -> str:
        int(v, 16)  # Raises ValueError if not valid hex
        return v.lower()

    @classmethod
    def compute(cls, data: bytes) -> "MerkleHash":
        """Calculates SHA-256 of byte array."""
        return cls(digest=hashlib.sha256(data).hexdigest())

    @classmethod
    def combine(cls, left: "MerkleHash", right: "MerkleHash") -> "MerkleHash":
        """Combines two hashes in canonical Merkle tree node order."""
        combined = hashlib.sha256(
            bytes.fromhex(left.digest) + bytes.fromhex(right.digest)
        ).hexdigest()
        return cls(digest=combined)


