import hashlib
import math
from typing import List, Tuple
from pydantic import BaseModel, ConfigDict, Field, field_validator


class GeoCoordinates(BaseModel):
    """Immutable WGS-84 geographic coordinate pair."""
    model_config = ConfigDict(strict=True, frozen=True)

    latitude: float = Field(..., ge=-90.0, le=90.0)
    longitude: float = Field(..., ge=-180.0, le=180.0)

    def haversine_distance_meters(self, other: "GeoCoordinates") -> float:
        """Computes great-circle distance between two coordinates in meters."""
        R = 6371000.0  # Earth radius in meters
        phi1 = math.radians(self.latitude)
        phi2 = math.radians(other.latitude)
        delta_phi = math.radians(other.latitude - self.latitude)
        delta_lambda = math.radians(other.longitude - self.longitude)

        a = (
            math.sin(delta_phi / 2.0) ** 2
            + math.cos(phi1) * math.cos(phi2) * (math.sin(delta_lambda / 2.0) ** 2)
        )
        c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))
        return R * c

    def to_wkt(self) -> str:
        """Returns OpenGIS Well-Known Text (WKT) POINT representation."""
        return f"POINT({self.longitude:.7f} {self.latitude:.7f})"


class EmbeddingVector(BaseModel):
    """Immutable 384-dimensional dense semantic embedding vector."""
    model_config = ConfigDict(strict=True, frozen=True)

    values: Tuple[float, ...] = Field(...)

    @field_validator("values")
    @classmethod
    def validate_dimension(cls, v: Tuple[float, ...]) -> Tuple[float, ...]:
        if len(v) != 384:
            raise ValueError(f"EmbeddingVector must have exactly 384 dimensions, got {len(v)}")
        return v

    def cosine_similarity(self, other: "EmbeddingVector") -> float:
        """Computes cosine similarity in [-1.0, 1.0]."""
        dot = sum(a * b for a, b in zip(self.values, other.values))
        norm_a = math.sqrt(sum(a * a for a in self.values))
        norm_b = math.sqrt(sum(b * b for b in other.values))
        if norm_a == 0.0 or norm_b == 0.0:
            return 0.0
        return dot / (norm_a * norm_b)

    def euclidean_distance(self, other: "EmbeddingVector") -> float:
        """Computes L2 Euclidean distance."""
        return math.sqrt(sum((a - b) ** 2 for a, b in zip(self.values, other.values)))

    @classmethod
    def zeros(cls) -> "EmbeddingVector":
        return cls(values=tuple(0.0 for _ in range(384)))


class MelSpectrogram(BaseModel):
    """Acoustic Mel spectrogram summary extracted by C++ DSP kernel."""
    model_config = ConfigDict(strict=True, frozen=True)

    energy_db: float
    spectral_entropy: float
    filterbank_energies: Tuple[float, ...] = Field(...)

    @field_validator("filterbank_energies")
    @classmethod
    def validate_filterbanks(cls, v: Tuple[float, ...]) -> Tuple[float, ...]:
        if len(v) != 16:
            raise ValueError(f"MelSpectrogram requires 16 filterbanks, got {len(v)}")
        return v


